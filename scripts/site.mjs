// Builds what the docs site runs: the real Office bundle and the lists and settings it shows. Run with `npm run site`
// (which builds first), and commit what changes in docs/.
import * as esbuild from "esbuild";
import * as fs from "fs";

fs.copyFileSync("dist/officeView.js", "docs/officeView.js");
fs.copyFileSync("dist/officeView.css", "docs/officeView.css");

const result = await esbuild.build({
  entryPoints: ["src/site/data.ts"],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "OFFICE_SITE_MODULE",
  platform: "browser",
  target: "es2022",
});
const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
const settings = Object.entries(pkg.contributes.configuration.properties).map(([key, spec]) => ({
  key,
  type: spec.type,
  default: spec.default,
  values: spec.enum,
  description: spec.markdownDescription ?? spec.description ?? "",
}));
const commands = pkg.contributes.commands.map((command) => ({ id: command.command, title: `${command.category}: ${command.title}` }));
fs.writeFileSync(
  "docs/siteData.js",
  `// Generated by scripts/site.mjs from the source and package.json. Don't edit.\n${result.outputFiles[0].text}` +
    `window.OFFICE_SITE = Object.assign(OFFICE_SITE_MODULE.OFFICE_SITE, ${JSON.stringify({ version: pkg.version, settings, commands })});\n`,
);
console.log("docs/officeView.js, docs/officeView.css, and docs/siteData.js updated");
